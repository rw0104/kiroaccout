import test from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { createRequire } from 'node:module'
import vm from 'node:vm'
import { verifyCrewManagedPackage } from '../../scripts/lib/crewManagedPackage.mjs'

const require = createRequire(import.meta.url)
const asar = require('@electron/asar')
const ts = require('typescript')

const prefix = 'resources/crew-managed/'
const hash = value => createHash('sha256').update(value).digest('hex')
function fixture() {
  const modules = [
    'kiro_crew.agent_sdk.kas_model_catalog', 'kiro_crew.acp.session_handle_model_selection',
    'kiro_crew.acp.session_handle_updates', 'kiro_crew.acp.session_handle_mcp',
    'kiro_crew.dashboard.server', 'kiro_crew.dashboard.server_runtime.api_entrypoint',
    'kiro_crew.dashboard.server_runtime.model_catalog_events'
  ]
  const files = new Map()
  const put = (path, text) => { files.set(prefix + path, Buffer.from(text)); return hash(text) }
  const manifest = {
    schemaVersion: 1,
    upstream: { name: 'KiroCrew', version: '0.12.0', commit: 'f315771db6a95704d129c7b722340a676d6bb8a4',
      url: 'https://github.com/kirodotdev/KiroCrew', license: 'Apache-2.0' },
    files: modules.map(module => {
      const path = `patches/${module.replaceAll('.', '/')}.py`
      return { module, path, sha256: put(path, `# Synthetic source for ${module}\n`),
        originalNormalizedSha256: module.endsWith('.model_catalog_events') ? null : 'f'.repeat(64) }
    }),
    supportFiles: [
      ['launcher.py', '# Synthetic launcher\n'], ['overlay.py', '# Synthetic loader\n'],
      ['LICENSE.KiroCrew', 'Apache License\nVersion 2.0\nSynthetic license fixture\n'],
      ['NOTICE.KiroCrew', 'KiroCrew\nSynthetic modified kiroaccout fixture\n']
    ].map(([path, text]) => ({ path, sha256: put(path, text) })),
    frontend: { asset: 'useWebSocket-SYNTHETIC.js', originalSha256: 'e'.repeat(64),
      path: 'frontend/useWebSocket-SYNTHETIC.js', sourcePath: 'frontend/useWebSocket.ts' }
  }
  manifest.frontend.sha256 = put(manifest.frontend.path, '// Synthetic browser asset\n')
  manifest.frontend.sourceSha256 = put(manifest.frontend.sourcePath, '// Synthetic corresponding source\n')
  const syncManifest = () => put('manifest.json', JSON.stringify(manifest) + '\n')
  syncManifest()
  const read = path => { assert.ok(files.has(path), `missing fixture: ${path}`); return files.get(path) }
  const args = () => ({ entries: ['resources/crew-managed', ...files.keys()], readPackaged: read,
    readUnpacked: read, readSource: read })
  return { files, manifest, args, syncManifest }
}

test('package admission checks the complete Crew source, runtime, license and frontend copies without execution', () => {
  const f = fixture()
  assert.deepEqual(verifyCrewManagedPackage(f.args()), {
    upstreamVersion: '0.12.0', patchModules: 7, resources: 14, licenseIncluded: true, frontendSourceIncluded: true
  })
})

test('missing or altered Crew resources cannot pass package verification', () => {
  for (const mutation of ['missing', 'altered', 'unpacked', 'stale-source']) {
    const f = fixture(), path = prefix + 'launcher.py'
    const args = f.args()
    if (mutation === 'missing') args.entries = args.entries.filter(entry => entry !== path)
    if (mutation === 'altered') f.files.set(path, Buffer.from('changed\n'))
    if (mutation === 'unpacked') args.readUnpacked = name => name === path ? Buffer.from('changed\n') : f.files.get(name)
    if (mutation === 'stale-source') args.readSource = name => name === path ? Buffer.from('changed\n') : f.files.get(name)
    assert.throws(() => verifyCrewManagedPackage(args), /missing|differs|stale/)
  }
})

test('undeclared credentials, private files and generated bytecode are rejected by the package inventory', () => {
  for (const extra of ['.local/credentials.json', 'secrets.enc', '__pycache__/launcher.pyc', 'debug-report.md']) {
    const f = fixture(), args = f.args()
    args.entries.push(prefix + extra)
    assert.throws(() => verifyCrewManagedPackage(args), /Undeclared/)
  }
})

test('a manifest cannot substitute modules, traverse paths or relax upstream provenance', () => {
  for (const mutation of ['module', 'traversal', 'duplicate', 'upstream']) {
    const f = fixture()
    if (mutation === 'module') f.manifest.files[0].module = '__proto__'
    if (mutation === 'traversal') f.manifest.files[0].path = '../other.py'
    if (mutation === 'duplicate') f.manifest.files[1] = { ...f.manifest.files[0] }
    if (mutation === 'upstream') f.manifest.upstream.license = 'unknown'
    f.syncManifest()
    assert.throws(() => verifyCrewManagedPackage(f.args()))
  }
})

test('private diagnostic material and platform-dependent line endings fail even with updated manifest hashes', () => {
  for (const text of ['# private-docs diagnostic\n', '# source\r\n']) {
    const f = fixture(), file = f.manifest.supportFiles.find(file => file.path === 'launcher.py')
    f.files.set(prefix + file.path, Buffer.from(text)); file.sha256 = hash(text); f.syncManifest()
    assert.throws(() => verifyCrewManagedPackage(f.args()), /Private diagnostic material|must use LF/)
  }
})

test('license and modification notices are mandatory payloads rather than optional build comments', () => {
  const f = fixture(), file = f.manifest.supportFiles.find(file => file.path === 'NOTICE.KiroCrew')
  f.files.set(prefix + file.path, Buffer.from('upstream only\n')); file.sha256 = hash('upstream only\n'); f.syncManifest()
  assert.throws(() => verifyCrewManagedPackage(f.args()), /KiroCrew/)
})

test('the production package-reader callbacks verify a real unpacked ASAR on the current operating system', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'crew-package-archive-'))
  const appRoot = join(directory, 'source'), resources = join(directory, 'packaged')
  const archive = join(resources, 'app.asar')
  t.after(() => { asar.uncache(archive); rmSync(directory, { recursive: true, force: true }) })
  mkdirSync(appRoot); mkdirSync(resources)
  const f = fixture()
  for (const [entry, content] of f.files) {
    const filename = join(appRoot, ...entry.split('/'))
    mkdirSync(dirname(filename), { recursive: true })
    writeFileSync(filename, content)
  }
  await asar.createPackageWithOptions(appRoot, archive, { unpackDir: 'resources' })
  const entries = asar.listPackage(archive).map(entry => entry.replaceAll('\\', '/').replace(/^\//, ''))

  // Execute the real verifier's call site, including its path conversion, so
  // a platform-specific ASAR API mismatch cannot hide behind a Map-only mock.
  const source = readFileSync(new URL('../../scripts/verify-platform-package.mjs', import.meta.url), 'utf8')
  const tree = ts.createSourceFile('verify-platform-package.mjs', source, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JS)
  let call
  const visit = node => {
    if (ts.isCallExpression(node) && node.expression.getText(tree) === 'verifyCrewManagedPackage') call = node.getText(tree)
    ts.forEachChild(node, visit)
  }
  visit(tree)
  assert.ok(call)
  const result = vm.runInNewContext(call, { verifyCrewManagedPackage, entries, asar, archive, resources, appRoot, join, readFileSync })
  assert.equal(result.resources, 14)
  assert.equal(result.patchModules, 7)
})
